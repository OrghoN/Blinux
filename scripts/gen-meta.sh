#!/usr/bin/env bash
# Generate pkgbuilds/blinux-meta/PKGBUILD from packages/*.txt.
#
# Usage:
#   scripts/gen-meta.sh           regenerate (bumps pkgrel if dependencies changed)
#   scripts/gen-meta.sh --check   exit 1 if the PKGBUILD is out of date (CI lint)
#
# One split package per stack list:
#   base.txt -> blinux-base, aster.txt -> blinux-aster, docs.txt -> blinux-docs,
#   hep.txt  -> blinux-hep,  ml.txt    -> blinux-ml,    ml-cuda.txt -> blinux-ml-cuda
# "@group" lines expand to the group's members, because pacman dependencies
# can't name groups.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/pkgbuilds/blinux-meta/PKGBUILD"
CHECK=0
[[ "${1:-}" == --check ]] && CHECK=1

declare -A DESC=(
    [base]="Blinux base stack: system, audio and speech, GNOME on Wayland, zsh, Emacs with Emacspeak, yay"
    [aster]="Blinux optional stack: AsTeR spoken math with Software DECtalk"
    [docs]="Blinux optional stack: TeX Live, pandoc and braille translation"
    [hep]="Blinux optional stack: high energy physics (ROOT, Geant4, Pythia8, FastJet, scikit-hep)"
    [ml]="Blinux optional stack: machine learning on the CPU (PyTorch, scikit-learn, Jupyter)"
    [ml-cuda]="Blinux optional stack: machine learning with CUDA (python-pytorch-cuda)"
)
STACKS=(base aster docs hep ml ml-cuda)

deps_for() {
    local name
    sed -e 's/#.*//' -e 's/[[:space:]]//g' -e '/^$/d' "$ROOT/packages/$1.txt" |
        while read -r name; do
            if [[ "$name" == @* ]]; then
                pacman -Sgq "${name#@}" || { echo "unknown group: $name" >&2; exit 1; }
            else
                echo "$name"
            fi
        done | sort -u
}

body() {
    # Everything except pkgrel, which depends on history.
    local s
    printf "pkgbase=blinux-meta\npkgname=("
    printf "'blinux-%s' " "${STACKS[@]}"
    printf ")\npkgver=0.1.0\n"
    printf "arch=('any')\nurl=\"https://github.com/OrghoN/Blinux\"\nlicense=('GPL-3.0-or-later')\n"
    for s in "${STACKS[@]}"; do
        printf '\npackage_blinux-%s() {\n  pkgdesc="%s"\n  depends=(\n' "$s" "${DESC[$s]}"
        deps_for "$s" | sed "s/.*/    '&'/"
        printf '  )\n}\n'
    done
}

new_body="$(body)"
old_body=""
old_rel=0
if [[ -f "$OUT" ]]; then
    old_body="$(sed -e '1,/^# --- generated/d' -e '/^pkgrel=/d' "$OUT")"
    old_rel="$(sed -n 's/^pkgrel=//p' "$OUT")"
fi

if ((CHECK)); then
    if [[ "$new_body" != "$old_body" ]]; then
        echo "pkgbuilds/blinux-meta/PKGBUILD is out of date with packages/*.txt: run make meta" >&2
        diff <(printf '%s\n' "$old_body") <(printf '%s\n' "$new_body") >&2 || true
        exit 1
    fi
    echo "blinux-meta is up to date"
    exit 0
fi

rel="$old_rel"
if [[ "$new_body" != "$old_body" ]]; then
    rel=$((old_rel + 1))
fi
mkdir -p "$(dirname "$OUT")"
{
    echo "# Maintainer: OrghoN <https://github.com/OrghoN>"
    echo "#"
    echo "# Generated by scripts/gen-meta.sh from packages/*.txt. Don't edit by hand:"
    echo "# change the lists and run \"make meta\"."
    echo "# --- generated"
    printf '%s\n' "$new_body" | sed "s/^pkgver=0.1.0$/pkgver=0.1.0\npkgrel=$rel/"
} >"$OUT"
(cd "$(dirname "$OUT")" && makepkg --printsrcinfo >.SRCINFO)
echo "wrote $OUT (pkgrel $rel)"
